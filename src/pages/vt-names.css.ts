import type { APIRoute } from 'astro';
import { getCollection } from 'astro:content';

/**
 * Shared-element View Transition names for every feature and issue, generated at build time.
 * Strict CSP rules out style="" attributes, so each element gets a class and this sheet maps
 * the class to its view-transition-name. A name may appear at most once per page.
 */
export const GET: APIRoute = async () => {
  const articles = await getCollection('articles');
  const issues = await getCollection('issues');
  const lines: string[] = ['/* generated by src/pages/vt-names.css.ts */'];

  for (const a of articles) {
    const key = `${a.data.issueNumber}-${a.data.articleSlug}`;
    lines.push(`.vt-hl-${key}{view-transition-name:hl-${key};view-transition-class:mo-headline}`);
    lines.push(`.vt-plate-${key}{view-transition-name:plate-${key};view-transition-class:mo-plate}`);
  }
  for (const i of issues) {
    const n = i.data.issueNumber;
    lines.push(`.vt-issue-art-${n}{view-transition-name:issue-art-${n};view-transition-class:mo-issue}`);
  }

  return new Response(lines.join('\n') + '\n', {
    headers: { 'Content-Type': 'text/css; charset=utf-8' }
  });
};
