import type { APIRoute } from 'astro';
import { getCollection } from 'astro:content';

/**
 * Shared-element View Transition names for every feature, issue, and persistent chrome element,
 * generated at build time. Strict CSP rules out style="" attributes, so elements match by class
 * or data attributes and this sheet maps each to a unique view-transition-name.
 * A name may appear at most once per page (verified by scripts/smoke-pages.mjs).
 */
export const GET: APIRoute = async () => {
  const articles = await getCollection('articles');
  const issues = await getCollection('issues');
  const lines: string[] = [
    '/* generated by src/pages/vt-names.css.ts */',
    '.press-masthead .si-badge{view-transition-name:si-badge;view-transition-class:mo-brand}',
    '.press-masthead .brand-title{view-transition-name:si-brand-title;view-transition-class:mo-brand}',
    '.masthead-datum-strip .live-issue-pill{view-transition-name:si-issue-chip;view-transition-class:mo-chip}',
    '.opus-read-stamp{view-transition-name:si-read-stamp;view-transition-class:mo-stamp}'
  ];

  for (const a of articles) {
    const key = `${a.data.issueNumber}-${a.data.articleSlug}`;
    const readId = `${a.data.issueNumber}/${a.data.articleSlug}`;
    lines.push(`.vt-hl-${key}{view-transition-name:hl-${key};view-transition-class:mo-headline}`);
    lines.push(`.vt-plate-${key}{view-transition-name:plate-${key};view-transition-class:mo-plate}`);
    lines.push(
      `[data-read-id="${readId}"] .service-stamp,[data-read-article="${readId}"] .article-opener-header .service-stamp{view-transition-name:chip-${key};view-transition-class:mo-chip}`
    );
    lines.push(
      `[data-read-id="${readId}"] .ledger-folio-col,[data-read-article="${readId}"] .article-breadcrumb-bar>.press-controls-bar:first-child>span.datum-tag{view-transition-name:folio-${key};view-transition-class:mo-chip}`
    );
    lines.push(
      `[data-read-id="${readId}"].is-read .opus-read-mark{view-transition-name:read-${key};view-transition-class:mo-stamp}`
    );
  }

  for (const i of issues) {
    const n = i.data.issueNumber;
    lines.push(`.vt-issue-art-${n}{view-transition-name:issue-art-${n};view-transition-class:mo-issue}`);
    lines.push(
      `.carbon-sheet>.opus-read-counter[data-read-counter="${n}"]{view-transition-name:read-counter-${n};view-transition-class:mo-stamp}`
    );
  }

  return new Response(lines.join('\n') + '\n', {
    headers: { 'Content-Type': 'text/css; charset=utf-8' }
  });
};
